import subprocess
import re
from pathlib import Path
import os
import glob

BASE_DIRECTORY = Path.cwd()

ICHEM_COMMAND = BASE_DIRECTORY / "../../../build-test/IChem"

PSEUDOATOM_DESCRIPTIONS = {
    "CA": "hydrophobic",
    "CZ": "aromatic",
    "O": "Hydrogen_bond (interacting protein atom is acceptor)",
    "OG": "Hydrogen_bond (interacting protein atom is both acceptor and donor)",
    "N": "Hydrogen_bond (interacting protein atom is donor)",
    "OD1": "Ionic (interacting protein atom is negatively charged)",
    "NZ": "Ionic (interacting protein atom is positively charged)",
    "ZN": "Metal coordination"
}

# Find mol2 files in interaction subdirectories
def find_mol2_pairs(base_dir):
    test_files = {}
    for subdir in Path(base_dir).iterdir():
        if subdir.is_dir():
            mol2_files = sorted(subdir.glob("*.mol2"))
            file_pairs = [(mol2_files[i], mol2_files[i + 1]) for i in range(0, len(mol2_files) - 1, 2)]
            test_files[subdir.name] = file_pairs
    return test_files

# Run IChem command
def run_chem_test(file_a, file_b):
    command = f"{ICHEM_COMMAND} ints {file_a} {file_b} result"
    result = subprocess.run(command, shell=True, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"IChem command failed: {result.stderr}")
    
    output_result = glob.glob("result*.mol2")
    if not output_result:
        raise FileNotFoundError("No result file generated by IChem")
    
    latest_file = max(output_result, key=os.path.getmtime)
    with open(latest_file, 'r') as file:
        return file.read()

# Parse Atoms from the output
def parse_atoms(output_text):
    pattern = r"@<TRIPOS>ATOM(.*?)@<TRIPOS>BOND" # Get everything between ATOM and BOND
    match = re.search(pattern, output_text, re.DOTALL)
    return match.group(1).strip() if match else None

# Parse interactions
def parse_interactions(output_text):
    detected_interactions = []
    atom_line = re.compile(r'^\s*\d+\s+(\S+)\s+')

    for line in output_text.splitlines():
        match = atom_line.match(line)
        if match:
            atom_name = match.group(1)
            if atom_name in PSEUDOATOM_DESCRIPTIONS:
                interaction = PSEUDOATOM_DESCRIPTIONS[atom_name]
                detected_interactions.append((atom_name, interaction))
    return detected_interactions

# Process test results
def process_test_results(file_a, file_b, interaction_type_file, atoms, output):
    if not output:
        return {
            "interaction_type": interaction_type_file,
            "file_a": file_a.name,
            "file_b": file_b.name,
            "interactions_found": None,
            "status": "Failed",
            "points": atoms
        }
    
    detected_interactions = parse_interactions(output)
    status = "Passed" if detected_interactions else "Failed"

    return {
        "interaction_type": interaction_type_file,
        "file_a": file_a.name,
        "file_b": file_b.name,
        "interactions_found": detected_interactions,
        "status": status,
        "points": atoms
    }

# Run all tests
def run_all_tests(base_dir):
    test_files = find_mol2_pairs(base_dir)
    results_summary = []

    for test_dir, file_pairs in test_files.items():
        for file_a, file_b in file_pairs:
            try:
                output = run_chem_test(file_a, file_b)
                atoms = parse_atoms(output)
                result = process_test_results(file_a, file_b, test_dir, atoms, output)
                results_summary.append(result)
            except Exception as e:
                results_summary.append({
                    "interaction_type": test_dir,
                    "file_a": file_a.name,
                    "file_b": file_b.name,
                    "interactions_found": None,
                    "status": "Failed",
                    "error_message": str(e),
                    "points": None
                })
    return results_summary

# Display results with the desired format
def display_results(results_summary):
    print("\n############## Test Summary ##############\n")
    total_tests = len(results_summary)
    passed_tests = [res for res in results_summary if res["status"] == "Passed"]
    failed_tests = [res for res in results_summary if res["status"] == "Failed"]

    print(f"Total tests: {total_tests}")
    print(f"Passed: {len(passed_tests)}")
    print(f"Failed: {len(failed_tests)}\n")
    print("\nDetailed Results:\n")

    for result in results_summary:
        print(f"Interaction Type: {result['interaction_type']}")
        print(f"File A: {result['file_a']}")
        print(f"File B: {result['file_b']}")
        print(f"Status: {result['status']}")

        if result["status"] == "Passed":
            interactions_found = result["interactions_found"]
            interaction_atoms = [interaction[0] for interaction in interactions_found]
            interaction_types = [interaction[1] for interaction in interactions_found]
            
            print("\nInteractions Found:")
            for atom, interaction_type in zip(interaction_atoms, interaction_types):
                print(f"  Atom: {atom} -> Interaction Type: {interaction_type}")

            print("\nPoints of Interaction:")
            points_lines = result["points"].splitlines()
            for line in points_lines:
                if any(atom in line for atom in interaction_atoms):
                    print(f"  {line.strip()}")

        print("\n" + "=" * 50 + "\n")


if __name__ == "__main__":
    base_dir = BASE_DIRECTORY
    all_results = run_all_tests(base_dir)
    display_results(all_results)
