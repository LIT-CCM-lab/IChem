#ifndef CHAIN_H
#define CHAIN_H
#include "global.h"

namespace ICMole
{

class Chain
{
    friend class Molecule;
    friend class Residu;
  private:
    /*!< \brief Name of the chain */
    std::string name;
    /*!< \brief List of residu included in this chain */
    ResiduList  residus;
    /*!< \brief Parent molecule */
    Molecule&   molecule;
    /*!< \brief Tell whether this chain should be used for analysis or not */
    bool         inUse;


    ////////////////////////////////////////////////
    ////////////////////////////////////////////////
    ///////////////// CONSTRUCTORS /////////////////
    ////////////////////////////////////////////////
    ////////////////////////////////////////////////
    Chain(Molecule &molecule, const std::string& Name) throw(MoleExcept);
    Chain( Molecule * const molecule, const std::string& Name) throw(MoleExcept);










////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////// RESIDUES //////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////

    /*!< \brief Add a residu to this chain */
    void addResidu(Residu* const res) throw(MoleExcept);


    /*!< \brief Delete a residu from this chain */
    void delResidu(Residu* const res) throw(MoleExcept);


public:

////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////// GENERICS //////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////

///// Getters:

    /*!< \brief Returns the number of residus in this chain */
inline            size_t getCountRes() const {return residus.size();}


    /*!< \brief Returns the name of the chain */
inline const std::string& getName()     const {return name;}


    /*!< \brief Returns the parent molecule */
inline         Molecule& getMolecule() const {return molecule;}

   /*!< \brief Check all residus to see if at least one is used */
    void checkUse();

    /*!< \brief Return true when the chain is used */
inline const bool& isUsed() const {return inUse;}


    /*!< \brief Define if the chain is used or not. Applied to all atoms, residus and bond if desired*/
    void setUse(const bool& use,const bool& applyto=true);


void setName(const std::string& new_name){name=new_name;}

////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////// ITERATOR //////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////

    /*!< \brief Returns a const_iterator over the first residu */
    ItCRes firstC() const         {return residus.begin();}


    /*!< \brief Returns a const_iterator over the last residu */
    ItCRes lastC()   const        {return residus.end();}


    /*!< \brief Returns an iterator over the first residu */
    ItRes first()             {return residus.begin();}


    /*!< \brief Returns an iterator over the last residu */
    ItRes  last()             {return residus.end();}


    Residu& getResidu(const size_t& pos) const throw(MoleExcept);







////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////// GENERICS //////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
///

    /*!< \brief Return a description of this chain */
    const std::string toString() const;

};

}

#endif // CHAIN_H
